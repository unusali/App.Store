import { relations } from 'drizzle-orm';
import { boolean, integer, jsonb, pgTable, serial, text, timestamp } from 'drizzle-orm/pg-core';

export const users = pgTable('users', {
  id: serial('id').primaryKey(),
  uid: text('uid').notNull().unique(),
  email: text('email').notNull(),
  fullName: text('full_name'),
  avatarUrl: text('avatar_url'),
  createdAt: timestamp('created_at').defaultNow().notNull(),
  updatedAt: timestamp('updated_at').defaultNow().notNull(),
});

export const brandSettings = pgTable('brand_settings', {
  id: serial('id').primaryKey(),
  userId: integer('user_id')
    .references(() => users.id, { onDelete: 'cascade' })
    .notNull(),
  brandName: text('brand_name').default('Default Brand').notNull(),
  logoUrl: text('logo_url'),
  primaryColor: text('primary_color').default('#0F172A').notNull(),
  accentColor: text('accent_color').default('#2563EB').notNull(),
  headingFont: text('heading_font').default('Plus Jakarta Sans').notNull(),
  bodyFont: text('body_font').default('DM Sans').notNull(),
  layoutTemplate: text('layout_template').default('executive_brief').notNull(),
  headerText: text('header_text').default('Confidential & Proprietary'),
  footerText: text('footer_text').default('Generated by DocuForge Document Intelligence'),
  isDefault: boolean('is_default').default(true).notNull(),
  createdAt: timestamp('created_at').defaultNow().notNull(),
  updatedAt: timestamp('updated_at').defaultNow().notNull(),
});

export const files = pgTable('files', {
  id: serial('id').primaryKey(),
  userId: integer('user_id')
    .references(() => users.id, { onDelete: 'cascade' })
    .notNull(),
  originalName: text('original_name').notNull(),
  mimeType: text('mime_type').notNull(),
  fileSizeBytes: integer('file_size_bytes').notNull(),
  extractionMethod: text('extraction_method').default('ocr_vision').notNull(),
  extractionStatus: text('extraction_status').default('completed').notNull(),
  extractedText: text('extracted_text').notNull(),
  pageCount: integer('page_count').default(1).notNull(),
  wordCount: integer('word_count').default(0).notNull(),
  metadata: jsonb('metadata').default({}).notNull(),
  createdAt: timestamp('created_at').defaultNow().notNull(),
});

export const generations = pgTable('generations', {
  id: serial('id').primaryKey(),
  userId: integer('user_id')
    .references(() => users.id, { onDelete: 'cascade' })
    .notNull(),
  fileId: integer('file_id')
    .references(() => files.id, { onDelete: 'cascade' })
    .notNull(),
  brandSettingId: integer('brand_setting_id').references(() => brandSettings.id, {
    onDelete: 'set null',
  }),
  outputType: text('output_type').notNull(), // 'summary' | 'qa' | 'paragraphs' | 'image_prompts' | 'formatted_document'
  title: text('title').notNull(),
  promptInstructions: text('prompt_instructions'),
  contentMarkdown: text('content_markdown').notNull(),
  structuredOutput: jsonb('structured_output').default({}).notNull(),
  modelUsed: text('model_used').default('gemini-3.8-flash').notNull(),
  createdAt: timestamp('created_at').defaultNow().notNull(),
});

export const usersRelations = relations(users, ({ many }) => ({
  brandSettings: many(brandSettings),
  files: many(files),
  generations: many(generations),
}));

export const brandSettingsRelations = relations(brandSettings, ({ one, many }) => ({
  user: one(users, {
    fields: [brandSettings.userId],
    references: [users.id],
  }),
  generations: many(generations),
}));

export const filesRelations = relations(files, ({ one, many }) => ({
  user: one(users, {
    fields: [files.userId],
    references: [users.id],
  }),
  generations: many(generations),
}));

export const generationsRelations = relations(generations, ({ one }) => ({
  user: one(users, {
    fields: [generations.userId],
    references: [users.id],
  }),
  file: one(files, {
    fields: [generations.fileId],
    references: [files.id],
  }),
  brandSetting: one(brandSettings, {
    fields: [generations.brandSettingId],
    references: [brandSettings.id],
  }),
}));
